import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const root=process.env.TASTEPRINT_TEST_URL||'http://127.0.0.1:4193/';
const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE||undefined,args:['--no-sandbox']});
try{
 for(const width of [375,1280]){
  const context=await browser.newContext({viewport:{width,height:950},reducedMotion:'reduce'});
  const page=await context.newPage(),errors=[],external=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(new URL(request.url()).origin!==new URL(root).origin)external.push(new URL(request.url()).origin);});
  await page.goto(root+'demo.html');
  await page.getByRole('heading',{name:'Find something you’d enjoy together.'}).waitFor();
  await page.evaluate(()=>localStorage.setItem('tasteprint.demo-preservation-check','untouched'));
  const before=await page.evaluate(()=>JSON.stringify(Object.entries(localStorage).sort()));
  await page.reload();
  assert.equal(await page.evaluate(()=>JSON.stringify(Object.entries(localStorage).sort())),before,'demo guide never seeds, clears or changes browser data');
  assert.equal(await page.locator('script').count(),0,'guide has no application, account or analytics scripts');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'guide fits mobile');
  for(const link of await page.locator('a[href]').evaluateAll(nodes=>nodes.map(node=>node.href)))assert.equal(new URL(link).origin,new URL(root).origin);
  if(process.env.TASTEPRINT_SCREENSHOT_DIR)await page.screenshot({path:process.env.TASTEPRINT_SCREENSHOT_DIR+`/demo-${width}.png`,fullPage:true});
  await page.getByRole('link',{name:'Start with your interests',exact:true}).click();
  await page.getByRole('heading',{name:'What do you actually enjoy?'}).waitFor();
  await page.getByLabel('Animation preference',{exact:true}).selectOption('liked');
  await page.getByLabel('Fantasy preference',{exact:true}).selectOption('liked');
  await page.getByRole('button',{name:'Save interests',exact:true}).click();
  await page.getByText('Interests saved on this browser. Nothing was shared.',{exact:true}).waitFor();
  await page.getByRole('link',{name:'Find specific things',exact:true}).click();
  await page.locator('[data-catalog-item=spring] [data-item-detail]').click();
  await page.getByRole('heading',{name:'Spring',exact:true}).waitFor();
  await page.getByRole('heading',{name:'Source and provenance'}).waitFor();
  await page.locator('[data-item-action=save][data-item-id=spring]').click();
  await page.getByRole('navigation',{name:'Main navigation',exact:true}).getByRole('link',{name:'Saved',exact:true}).click();
  await page.locator('[data-catalog-item=spring]').waitFor();
  await page.getByRole('navigation',{name:'Main navigation',exact:true}).getByRole('link',{name:'Together',exact:true}).click();
  await page.getByRole('button',{name:'Use sample friend',exact:true}).click();
  await page.getByRole('heading',{name:'Invented sample friend',exact:true}).waitFor();
  assert.match(await page.locator('.common-ground').innerText(),/Animation/);
  assert.match(await page.locator('.common-ground').innerText(),/Fantasy/);
  await page.locator('[data-suggest-item=spring]').click();
  await page.getByText('Explore demo decision steps (no remote responses)',{exact:true}).click();
  await page.getByRole('button',{name:'I am interested',exact:true}).click();
  await page.getByRole('button',{name:'Simulate friend interest',exact:true}).click();
  await page.getByLabel('Proposed date, time and place (local only)').fill('Friday 7pm, invented demo living room');
  await page.getByRole('button',{name:'Propose details / request reapproval',exact:true}).click();
  await page.getByRole('button',{name:'I agree to these details',exact:true}).click();
  await page.getByRole('button',{name:'Simulate friend agreeing',exact:true}).click();
  assert.match(await page.locator('#shared-plan').innerText(),/State: scheduled/);
  await page.getByLabel('Proposed date, time and place (local only)').fill('Saturday 7pm, invented demo living room');
  await page.getByRole('button',{name:'Propose details / request reapproval',exact:true}).click();
  assert.match(await page.locator('#shared-plan').innerText(),/State: mutual_interest/,'material edit resets simulated approvals');
  await page.getByText('More',{exact:true}).click();
  await page.getByRole('link',{name:'Demo guide',exact:true}).click();
  await page.getByRole('heading',{name:'Find something you’d enjoy together.'}).waitFor();
  await page.getByRole('link',{name:'Fictional company profile',exact:true}).click();
  await page.getByText('Ownership not verified',{exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>localStorage.getItem('tasteprint.demo-preservation-check')),'untouched');
  assert.deepEqual(external,[],'demo walkthrough makes no remote requests');
  assert.deepEqual(errors,[]);
  await context.close();
 }
 console.log('Demo PASS: mobile/desktop guide → real Passport → specific item → Saved → sample friend → simulated agreement → reapproval; no guide storage writes, remote requests or page errors.');
}finally{await browser.close();}
